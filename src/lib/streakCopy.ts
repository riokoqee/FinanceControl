export function streakMessage(message: string, values: Record<string, string | number>): string {
  return message.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token));
}

const russianPlural = new Intl.PluralRules("ru");

export function streakDayLabel(count: number, language: Language): string {
  const t = streakCopy[language];
  const plural = language === "ru" ? russianPlural.select(count) : count === 1 ? "one" : "other";
  return `${count} ${plural === "one" ? t.dayOne : plural === "few" ? t.dayFew : t.dayMany}`;
}
